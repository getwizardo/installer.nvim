---@class InstallerConfig
local M = {}

---@class InstallerOptions
M.defaults = {
  -- YAML configuration files. Everything in this table can also be written in
  -- YAML (same keys). Precedence: defaults < global file < project file < setup() opts.
  config = {
    -- Global file (created by `:Installer config`).
    global = vim.fn.stdpath("config") .. "/installer.yaml",
    -- Project file name, searched upwards from the current working directory.
    -- Read through `vim.secure.read` (you are asked to trust it once).
    project = "installer.yaml",
  },

  -- Where generated spec files are written.
  -- * nil      -> auto-detect from lazy.nvim (`{ import = "plugins" }`), falling back
  --               to `stdpath("config") .. "/lua/plugins"`.
  -- * string   -> an explicit directory.
  -- * function -> `fun(): string` returning a directory.
  ---@type string|fun():string|nil
  plugins_dir = nil,

  -- What to do after a spec file is written:
  -- "install" -> reload lazy.nvim specs and run `:Lazy install` for the plugin
  -- "edit"    -> open the generated file in the current window
  -- "none"    -> only write the file
  ---@type "install"|"edit"|"none"
  after_write = "install",

  -- Ask before overwriting an existing spec file.
  confirm_overwrite = true,

  -- Add a `-- generated by installer.nvim` header to created files.
  header = true,

  -- Floating window options shared by the modal and the browser.
  ui = {
    border = "rounded",
    width = 0.6, -- number of columns, or a fraction of the editor width
    height = 0.7, -- number of rows, or a fraction of the editor height (browser only)
    winblend = 0,
  },

  -- GitHub search settings (used by `:Installer browse`).
  github = {
    -- Token used for the GitHub REST API. Raises the search rate limit from
    -- 10 to 30 requests/minute. Resolution order: this option, the token saved
    -- by `:Installer login`, $GITHUB_TOKEN / $GH_TOKEN, `gh auth token`.
    ---@type string|fun():string|nil
    token = nil,
    -- OAuth app client id for `:Installer login` -> "Browser sign-in" (device flow).
    -- Create one at https://github.com/settings/developers and enable "Device Flow".
    ---@type string|nil
    client_id = nil,
    -- Scopes requested by the device flow (public_repo is needed to star repos).
    scope = "public_repo read:user",
    -- Sign in automatically (using any available token) when the browser opens.
    auto_login = true,
    -- Appended to every search query unless `broad` mode is toggled on.
    -- See https://docs.github.com/en/search-github/searching-on-github/searching-for-repositories
    topic_query = "topic:neovim-plugin",
    -- Query used when broad mode is enabled (plugins that forgot the topic).
    broad_query = "neovim in:name,description,topics",
    -- Results per page (max 100).
    per_page = 30,
    -- Default sort: "stars" | "updated" | "best-match"
    sort = "stars",
    -- Debounce (ms) between typing in the prompt and sending a request.
    debounce = 450,
  },

  -- AI coding presets (`:Installer ai`). Disabled by default.
  ai = {
    enabled = false,
    -- Hide presets from the list by repo name, e.g. { "github/copilot.vim" }.
    ---@type string[]
    exclude = {},
  },

  -- mason.nvim integration (`:Installer mason`): LSP servers, DAP adapters,
  -- linters, formatters, compilers and runtimes from the Mason registry.
  mason = {
    -- Packages (Mason names or lspconfig server names) installed by
    -- `:Installer mason ensure`; `:Installer mason export` fills this list.
    ---@type string[]
    ensure_installed = {},
    -- Run `ensure` automatically after setup() when mason.nvim is available.
    auto_ensure = false,
    -- Refresh the registry once per session before the first use.
    refresh_registry = true,
    -- Parallel installs for `ensure` / multi-select installs.
    concurrency = 2,
    -- Open the :Mason window after a package finished installing.
    open_ui_on_install = false,
  },

  -- Local plugin cache (`:Installer cache`). Installed plugins are archived to
