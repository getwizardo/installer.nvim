import { json, type RequestEvent } from "@sveltejs/kit";
import masonRegistry from "#lib/server/data/masonRegistry.json";
import { saveSpecToDisk } from "#lib/server/luaBridge";

export const prerender = false;

interface MasonPackage {
  name: string;
  description: string;
  homepage?: string;
  categories: string[];
  languages: string[];
  lspconfig: string | null;
  source_id?: string;
  bin: string[];
}

export async function GET({ url }: RequestEvent) {
  const sp = url.searchParams;
  const q = (sp.get("q") || "").toLowerCase().trim();
  const category = (sp.get("category") || "ALL").toUpperCase();
  const language = (sp.get("language") || "").toLowerCase().trim();

  let packages = masonRegistry.packages as unknown as MasonPackage[];
  if (category && category !== "ALL") {
    packages = packages.filter((p) =>
      (p.categories || []).some((c) => c.toUpperCase() === category)
    );
  }
  if (language) {
    packages = packages.filter((p) =>
      (p.languages || []).some((l) => l.toLowerCase() === language)
    );
  }
  if (q) {
    packages = packages.filter(
      (p) =>
        p.name.toLowerCase().includes(q) ||
        (p.lspconfig && p.lspconfig.toLowerCase().includes(q)) ||
        (p.description && p.description.toLowerCase().includes(q)) ||
        (p.languages || []).some((l) => l.toLowerCase().includes(q))
    );
  }

  return json({
    ok: true,
    total: packages.length,
    packages,
  });
}

export async function POST({ request }: RequestEvent) {
  try {
    const body = await request.json();
    const names = Array.isArray(body.packages)
      ? (body.packages as string[])
      : [];
    const save = Boolean(body.save);
    const allPackages = masonRegistry.packages as unknown as MasonPackage[];
    const selected = allPackages.filter((p) => names.includes(p.name));
    const lspNames = selected.map((p) => p.lspconfig).filter(Boolean) as string[];
    const toolNames = selected.map((p) => p.name);

    const lines = [
      `-- Generated by Starsky for Neovim (SvelteKit) · ${selected.length} Mason package(s)`,
      "return {",
      "  {",
      '    "williamboman/mason.nvim",',
      `    opts = { ensure_installed = { ${toolNames.map((n) => JSON.stringify(n)).join(", ")} } },`,
      "  },",
    ];

    if (lspNames.length > 0) {
      lines.push(
        "  {",
        '    "williamboman/mason-lspconfig.nvim",',
        '    dependencies = { "williamboman/mason.nvim", "neovim/nvim-lspconfig" },',
        `    opts = { ensure_installed = { ${lspNames.map((n) => JSON.stringify(n)).join(", ")}${lspNames.length > 0 ? ", " : ""} }, automatic_installation = true },`,
        "  },"
      );
    }

    lines.push("}\n");
    const source = lines.join("\n");

    if (save) {
      const saved = await saveSpecToDisk({
        repo: "williamboman/mason.nvim",
        file: "mason-servers",
        dependencies:
          lspNames.length > 0
            ? "williamboman/mason-lspconfig.nvim, neovim/nvim-lspconfig"
            : "",
        opts: `{ ensure_installed = { ${toolNames.map((n) => JSON.stringify(n)).join(", ")} } }`,
      });
      return json({
        ok: true,
        source,
        lspNames,
        toolNames,
        saved,
      });
    }

    return json({
      ok: true,
      source,
      lspNames,
      toolNames,
    });
  } catch (err) {
    return json(
      { ok: false, error: err instanceof Error ? err.message : String(err) },
      { status: 400 }
    );
  }
}
