import { callNvim, type NvimAction } from "./nvim";
import fs from "fs";
import os from "os";
import path from "path";

export interface KaeruForm {
  repo: string;
  file?: string;
  name?: string;
  lazy?: string;
  priority?: string;
  event?: string;
  cmd?: string;
  ft?: string;
  keys?: string;
  dependencies?: string;
  branch?: string;
  tag?: string;
  version?: string;
  commit?: string;
  build?: string;
  opts?: string;
  config?: string;
  init?: string;
  pin?: string;
  cond?: string;
  enabled?: string;
}

export interface GeneratedSpec {
  source: string;
  name: string;
  file: string;
  short?: string;
}

export interface SavedSpecFile {
  file: string;
  filename: string;
  path: string;
  relativePath: string;
  size: number;
  mtime: string;
  source: string;
  repo: string;
}

export function getRepoRoot(): string {
  const cwd = process.cwd();
  if (fs.existsSync(path.join(cwd, "lua", "kaeru", "init.lua"))) {
    return cwd;
  }
  const parent = path.resolve(cwd, "..");
  if (fs.existsSync(path.join(parent, "lua", "kaeru", "init.lua"))) {
    return parent;
  }
  return cwd;
}

/**
 * Default spec directory without asking Neovim: `$XDG_CONFIG_HOME/nvim/lua/plugins`
 * (lazy.nvim's default). Used when Neovim is not available.
 */
export function fallbackPluginsDir(customDir?: string): string {
  if (customDir && customDir.trim() !== "") {
    const trimmed = customDir.trim();
    return path.isAbsolute(trimmed) ? trimmed : path.join(getRepoRoot(), trimmed);
  }
  const xdg = process.env.XDG_CONFIG_HOME?.trim();
  const configHome = xdg ? xdg : path.join(os.homedir(), ".config");
  return path.join(configHome, "nvim", "lua", "plugins");
}

/**
 * The directory `:Kaeru save` writes to. With Neovim available this asks the
 * Lua side (`kaeru.lazy`.plugins_dir), the same resolution `:Kaeru save` uses, so
 * web-saved specs land where lazy.nvim loads them. Otherwise it falls back to
 * the default config path.
 */
export async function resolvePluginsDir(customDir?: string): Promise<string> {
  if (customDir && customDir.trim() !== "") {
    return fallbackPluginsDir(customDir);
  }
  try {
    const res = await callNvim<{ ok: boolean; dir?: string }>(getRepoRoot(), "plugins_dir", {});
    if (res && res.ok && res.dir) {
      return res.dir;
    }
  } catch {
    // no Neovim on this machine: use the default below
  }
  return fallbackPluginsDir();
}


export async function runLuaBridge<T = Record<string, unknown>>(
  action: NvimAction,
  payload: Record<string, unknown>
): Promise<T> {
  const repoRoot = getRepoRoot();
  try {
    return await callNvim<T>(repoRoot, action, payload);
  } catch (err) {
    // No nvim on this machine (or it crashed): spec generation still works
    // with the TypeScript port; parse/complete need the real Lua modules.
    if (action === "spec_generate") {
      return buildSpecInTypeScript(payload.form as KaeruForm) as T;
    }
    const message = err instanceof Error ? err.message : String(err);
    return { ok: false, items: [], error: `Neovim bridge unavailable: ${message}` } as T;
  }
}

/**
 * Pure-TypeScript fallback generator so spec creation & saving never fail
 * even if Python/lupa is unavailable.
 */
export function buildSpecInTypeScript(form: KaeruForm): {
  ok: boolean;
  generated?: GeneratedSpec;
  error?: string;
} {
  let repo = (form.repo || "").trim().replace(/[,;]+$/, "").trim();
  if (
    (repo.startsWith('"') && repo.endsWith('"')) ||
    (repo.startsWith("'") && repo.endsWith("'"))
  ) {
    repo = repo.slice(1, -1).trim();
  }
  if (!repo) {
    return { ok: false, error: "Repository is required (owner/repo or a git URL)" };
  }

  let shortRepo: string | undefined;
  let urlRepo: string | undefined;
  let baseName = repo;

  const ghMatch =
    repo.match(/^https?:\/\/github\.com\/([\w_.-]+)\/([\w_.-]+)\/?$/) ||
    repo.match(/^git@github\.com:([\w_.-]+)\/([\w_.-]+)$/) ||
    repo.match(/^([\w_.-]+)\/([\w_.-]+)$/);

  if (ghMatch) {
    const owner = ghMatch[1];
    const cleanRepo = ghMatch[2].replace(/\.git$/, "");
    shortRepo = `${owner}/${cleanRepo}`;
    baseName = cleanRepo;
  } else if (/^[a-z][\w+.-]*:\/\//i.test(repo) || repo.startsWith("git@")) {
    urlRepo = repo;
    baseName = (repo.split(/[/:]/).pop() || "plugin").replace(/\.git$/, "");
  } else {
    return {
      ok: false,
      error: `Invalid repository "${repo}". Use owner/repo or a full git URL`,
    };
  }

  let defaultFile = baseName
    .toLowerCase()
    .replace(/\.n?vim$/, "")
    .replace(/^n?vim-/, "")
    .replace(/-n?vim$/, "")
    .replace(/[^a-z0-9_-]/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");
  if (!defaultFile) defaultFile = "plugin";

  const file = ((form.file || "").trim() || defaultFile).replace(/\.lua$/, "");
  if (file.includes("/") || file.includes("\\")) {
    return { ok: false, error: "File name must not contain path separators" };
  }

  const lines: string[] = [
    `-- Generated by kaeru.nvim on ${new Date().toISOString().slice(0, 10)}`,
    "-- Spec reference: https://lazy.folke.io/spec",
    "return {",
  ];

  if (shortRepo) {
    lines.push(`  ${JSON.stringify(shortRepo)},`);
  } else if (urlRepo) {
    lines.push(`  url = ${JSON.stringify(urlRepo)},`);
  }

  const name = (form.name || "").trim() || baseName;
  if ((form.name || "").trim()) {
    lines.push(`  name = ${JSON.stringify(form.name!.trim())},`);
  }

  const parseBool = (v?: string): boolean | undefined => {
    const s = (v || "").trim().toLowerCase();
    if (["true", "yes", "1", "on"].includes(s)) return true;
    if (["false", "no", "0", "off"].includes(s)) return false;
    return undefined;
  };

  const lazyVal = parseBool(form.lazy);
  if (lazyVal !== undefined) lines.push(`  lazy = ${lazyVal},`);

  if ((form.priority || "").trim()) {
    const n = Number(form.priority!.trim());
    if (Number.isNaN(n)) {
      return { ok: false, error: "Priority must be a number" };
    }
    lines.push(`  priority = ${n},`);
  }

  if ((form.version || "").trim()) {
    const v = form.version!.trim();
    lines.push(`  version = ${v === "false" ? "false" : JSON.stringify(v)},`);
  }

  for (const k of ["branch", "tag", "commit"] as const) {
    const v = (form[k] || "").trim();
    if (v) lines.push(`  ${k} = ${JSON.stringify(v)},`);
  }

  if (parseBool(form.pin) === true) {
    lines.push("  pin = true,");
  }

  const renderCsvOrTable = (key: string, rawVal?: string, alwaysList = false) => {
    const v = (rawVal || "").trim();
    if (!v) return;
    if (v.startsWith("{")) {
      lines.push(`  ${key} = ${v},`);
      return;
    }
    const parts = v
      .split(",")
      .map((s) => s.trim())
      .filter(Boolean);
    if (parts.length === 0) return;
    if (parts.length === 1 && !alwaysList) {
      lines.push(`  ${key} = ${JSON.stringify(parts[0])},`);
    } else if (parts.length === 1 && alwaysList) {
      lines.push(`  ${key} = { ${JSON.stringify(parts[0])} },`);
    } else {
      lines.push(`  ${key} = {`);
      for (const p of parts) {
        lines.push(`    ${JSON.stringify(p)},`);
      }
      lines.push("  },");
    }
  };

  renderCsvOrTable("event", form.event);
  renderCsvOrTable("cmd", form.cmd);
  renderCsvOrTable("ft", form.ft);
  renderCsvOrTable("keys", form.keys, true);
  renderCsvOrTable("dependencies", form.dependencies, true);

  if ((form.build || "").trim()) {
    const b = form.build!.trim();
    if (b.startsWith("{") || b.startsWith("function")) {
      lines.push(`  build = ${b},`);
    } else {
      lines.push(`  build = ${JSON.stringify(b)},`);
    }
  }

  if ((form.opts || "").trim()) {
    let o = form.opts!.trim();
    if (!o.startsWith("{")) o = `{ ${o} }`;
    lines.push(`  opts = ${o},`);
  }

  if ((form.init || "").trim()) {
    lines.push(`  init = ${form.init!.trim()},`);
  }

  if ((form.config || "").trim()) {
    const c = form.config!.trim();
    const lc = c.toLowerCase();
    if (lc === "function" || lc === "fn" || lc === "func") {
      lines.push(
        `  config = function(_, opts)\n    -- require("${defaultFile}").setup(opts)\n  end,`
      );
    } else if (lc.startsWith("function")) {
      lines.push(`  config = ${c},`);
    } else {
      const b = parseBool(c);
      if (b !== undefined) {
        lines.push(`  config = ${b},`);
      }
    }
  }

  lines.push("}\n");

  return {
    ok: true,
    generated: {
      source: lines.join("\n"),
      name,
      file,
      short: shortRepo,
    },
  };
}

export async function generateSpec(form: KaeruForm): Promise<{
  ok: boolean;
  generated?: GeneratedSpec;
  error?: string;
}> {
  const res = await runLuaBridge<{
    ok: boolean;
    generated?: GeneratedSpec;
    error?: string;
  }>("spec_generate", { form });
  if (res && res.ok && res.generated) {
    return res;
  }
  if (res && res.error) {
    return res;
  }
  return buildSpecInTypeScript(form);
}

export async function saveSpecToDisk(
  form: KaeruForm,
  customDir?: string,
  opts: { overwrite?: boolean } = {}
): Promise<{
  ok: boolean;
  exists?: boolean;
  path?: string;
  relativePath?: string;
  file?: string;
  generated?: GeneratedSpec;
  savedSpecs?: SavedSpecFile[];
  error?: string;
}> {
  const genRes = await generateSpec(form);
  if (!genRes.ok || !genRes.generated) {
    return { ok: false, error: genRes.error || "Invalid plugin spec" };
  }

  const dir = await resolvePluginsDir(customDir);
  try {
    fs.mkdirSync(dir, { recursive: true });
    const filename = `${genRes.generated.file}.lua`;
    const fullPath = path.join(dir, filename);
    if (fs.existsSync(fullPath) && !opts.overwrite) {
      return {
        ok: false,
        exists: true,
        path: fullPath,
        file: genRes.generated.file,
        error: `${filename} already exists in ${dir}. Overwrite it?`,
      };
    }
    fs.writeFileSync(fullPath, genRes.generated.source, "utf8");
    const repoRoot = getRepoRoot();
    const relativePath = fullPath.startsWith(repoRoot)
      ? path.relative(repoRoot, fullPath)
      : fullPath;

    return {
      ok: true,
      path: fullPath,
      relativePath,
      file: genRes.generated.file,
      generated: genRes.generated,
      savedSpecs: await listSavedSpecs(customDir),
    };
  } catch (err) {
    return {
      ok: false,
      error: err instanceof Error ? err.message : String(err),
    };
  }
}

export async function listSavedSpecs(customDir?: string): Promise<SavedSpecFile[]> {
  const dir = await resolvePluginsDir(customDir);
  if (!fs.existsSync(dir)) {
    return [];
  }
  const repoRoot = getRepoRoot();
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  const out: SavedSpecFile[] = [];
  for (const entry of entries) {
    if (entry.isFile() && entry.name.endsWith(".lua")) {
      const fullPath = path.join(dir, entry.name);
      const stat = fs.statSync(fullPath);
      const source = fs.readFileSync(fullPath, "utf8");
      const repoMatch =
        source.match(/return\s*\{\s*["']([^"']+\/[^"']+)["']/) ||
        source.match(/url\s*=\s*["']([^"']+)["']/);
      out.push({
        file: entry.name.replace(/\.lua$/, ""),
        filename: entry.name,
        path: fullPath,
        relativePath: fullPath.startsWith(repoRoot)
          ? path.relative(repoRoot, fullPath)
          : fullPath,
        size: stat.size,
        mtime: stat.mtime.toISOString(),
        source,
        repo: repoMatch ? repoMatch[1] : entry.name.replace(/\.lua$/, ""),
      });
    }
  }
  out.sort((a, b) => b.mtime.localeCompare(a.mtime));
  return out;
}

export async function deleteSavedSpec(file: string, customDir?: string): Promise<boolean> {
  const clean = file.replace(/\.lua$/, "").replace(/[/\\]/g, "");
  const fullPath = path.join(await resolvePluginsDir(customDir), `${clean}.lua`);
  if (fs.existsSync(fullPath)) {
    fs.unlinkSync(fullPath);
    return true;
  }
  return false;
}
