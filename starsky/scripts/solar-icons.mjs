// Generates src/lib/client/solar.ts: the subset of the Solar icon set (CC-BY-4.0,
// https://icon-sets.iconify.design/solar/) that the Starsky UI uses. Only those
// icons are bundled, so the client stays small. Run after changing ICONS:
//   npm run icons
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, "..", "src", "lib", "client", "solar.ts");

/** Icon names in the Solar "linear" style, grouped by where the UI uses them. */
export const ICONS = [
  // tabs
  "code-square-linear",
  "document-text-linear",
  "global-linear",
  "pen-new-square-linear",
  "add-square-linear",
  "box-linear",
  "cloud-upload-linear",
  "music-note-2-linear",
  "magnifier-linear",
  // actions and status
  "play-linear",
  "pause-linear",
  "skip-previous-linear",
  "skip-next-linear",
  "volume-loud-linear",
  "diskette-linear",
  "trash-bin-trash-linear",
  "folder-linear",
  "folder-open-linear",
  "file-linear",
  "refresh-linear",
  "close-circle-linear",
  "check-circle-linear",
  "danger-triangle-linear",
  "star-linear",
  "keyboard-linear",
  "download-linear",
  "folder-with-files-linear",
  "server-square-linear",
  "radio-linear",
  "cpu-linear",
  "programming-linear",
  "shield-check-linear",
  "align-left-linear",
  "code-2-linear",
  "menu-dots-linear",
  "link-round-linear",
  "notebook-linear",
  "bolt-linear",
  "record-linear",
  "stop-linear",
];

const icons = require("@iconify-json/solar/icons.json");
const defaults = { width: icons.width ?? 24, height: icons.height ?? 24 };

const missing = ICONS.filter((name) => !icons.icons[name]);
if (missing.length) {
  console.error(`solar-icons: unknown icon names: ${missing.join(", ")}`);
  process.exit(1);
}

const entries = ICONS.map((name) => {
  const icon = icons.icons[name];
  const width = icon.width ?? defaults.width;
  const height = icon.height ?? defaults.height;
  return `  ${JSON.stringify(name)}: { body: ${JSON.stringify(icon.body)}, width: ${width}, height: ${height} },`;
});

const source = `// Generated by scripts/solar-icons.mjs from @iconify-json/solar (CC-BY-4.0). Do not edit by hand.
export const SOLAR_ICONS = {
${entries.join("\n")}
} as const;

export type SolarIconName = keyof typeof SOLAR_ICONS;
`;

writeFileSync(out, source);
console.log(`solar-icons: wrote ${ICONS.length} icons to ${path.relative(process.cwd(), out)}`);
